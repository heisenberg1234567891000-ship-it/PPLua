-- In-game smoke test for the PPLua API. Results go to BepInEx/LogOutput.log as "PROBE ..." lines.
local passed, failed = 0, 0
local function check(name, fn)
  local ok, err = pcall(fn)
  if ok then passed = passed + 1; print("PROBE PASS " .. name)
  else failed = failed + 1; print("PROBE FAIL " .. name .. ": " .. tostring(err)) end
end
local function expect(cond, msg) if not cond then error(msg or "expectation failed", 2) end end

check("sandbox: no io/os.execute/load", function()
  expect(io == nil and load == nil and dofile == nil and os.execute == nil and debug == nil)
end)
check("sandbox: assets outside the mod are refused", function()
  expect(not pcall(ppg.sprite, "../Homelander/icon.png"))
  expect(not pcall(ppg.sprite, "C:/Windows/win.ini"))
  expect(not pcall(ppg.sound, "main.lua"))
end)
check("world calls refused before a map", function() expect(not pcall(ppg.spawn, "Brick")) end)

ppg.register_item{
  original = "Brick", name = "Probe Brick", description = "probe", category = "Misc.",
  after_spawn = function(obj) obj:color(1, 0, 1); obj.name = "Probe Brick (lua)" end,
}

local spawned_events = 0
ppg.on("spawn", function(obj, name) if name == "Probe Brick" then spawned_events = spawned_events + 1 end end)

ppg.on("map_loaded", function()
  print("PROBE categories: " .. table.concat(ppg.categories(), ", "))
  local items = ppg.spawnables()
  print("PROBE spawnables: " .. #items)
  print("PROBE particles: " .. table.concat(ppg.particles(), ", "))
  print("PROBE materials: " .. table.concat(ppg.materials(), ", "))

  local brick, probe, human
  check("spawnables include vanilla and modded items", function()
    local seen = {}
    for _, n in ipairs(items) do seen[n] = true end
    expect(seen["Brick"] and seen["Probe Brick"] and seen["Homelander"], "missing Brick / Probe Brick / Homelander")
  end)
  check("spawn vanilla brick", function()
    brick = ppg.spawn("Brick", -4, 6)
    expect(brick and brick:exists(), "no brick")
    expect(math.abs(brick.x + 4) < 0.5 and math.abs(brick.y - 6) < 0.5, "position " .. brick.x .. "," .. brick.y)
    expect(brick.spawnable == "Brick", "spawnable=" .. tostring(brick.spawnable))
  end)
  check("spawn modded item runs after_spawn and the spawn event", function()
    probe = ppg.spawn("Probe Brick", -2, 6)
    expect(probe.name == "Probe Brick (lua)", "name=" .. probe.name)
    expect(spawned_events >= 1, "spawn events=" .. spawned_events)
  end)
  check("object fields and setters", function()
    brick.vx = 3; expect(math.abs(brick.vx - 3) < 0.01)
    brick.temperature = 50; expect(math.abs(brick.temperature - 50) < 0.01)
    brick.mass = 2; expect(math.abs(brick.mass - 2) < 0.01)
    expect(brick.width > 0 and brick.height > 0)
    expect(not pcall(function() brick.on_fire = true end), "read-only field accepted a write")
    expect(not pcall(function() brick.nonsense = 1 end), "unknown field accepted a write")
    expect(getmetatable(brick) == "object", "metatable not locked")
    expect(tostring(brick):find("object%("), tostring(brick))
  end)
  check("handles are stable", function()
    local objs = ppg.objects()
    local found = false
    for _, o in ipairs(objs) do if o == brick then found = true end end
    expect(found, "ppg.objects() does not contain the same brick handle")
  end)
  check("find and raycast", function()
    local near = ppg.find(brick.x, brick.y, 1)
    expect(#near >= 1, "find returned nothing")
    local hit = ppg.raycast(brick.x, brick.y + 3, 0, -1, 10)
    expect(hit ~= nil, "raycast hit nothing")
  end)
  check("spawn human and read limbs", function()
    human = ppg.spawn("Human", 2, 6)
    local person = human:person()
    expect(person and person.alive, "no living person")
    local limbs = person:limbs()
    expect(#limbs > 5, "limbs=" .. #limbs)
    local head = person:limb("Head")
    expect(head and head.has_brain, "no head with brain")
    limbs[#limbs]:break_bone()
    expect(limbs[#limbs].broken, "bone did not break")
  end)
  check("context button and hooks attach", function()
    probe:button("Probe", function() end)
    probe:on_use(function() end)
    probe:on_update(function() end)
  end)
  check("storage round trip", function()
    ppg.save({ n = 42, s = "x" })
    local t = ppg.load()
    expect(t and t.n == 42 and t.s == "x")
  end)
  check("layout dump and new 0.2 API", function()
    local guy = ppg.spawn("Human", 6, 6):person()
    print("PROBE poses: " .. table.concat(guy:pose_names(), ", "))
    for _, l in ipairs(guy:limbs()) do
      local w, h = l:skin_size()
      local o = l:object()
      print(string.format("PROBE limb %s skin=%dx%d strength=%.1f toughness=%.1f regen=%.1f", l.name, w, h, l.strength, l.toughness, l.regeneration))
    end
    guy.pose = "Rest"; expect(guy.pose == "Rest", "pose not set")
    guy.pose = nil; expect(guy.pose == nil, "pose not cleared")
    local b = ppg.beam{ r = 1, g = 0, b = 0, width = 0.05, light = true }
    b:set(0, 2, 5, 2); expect(b.visible); b.visible = false; expect(not b.visible)
    local spr = ppg.sprite("pixel.png", 1, true, 0.5, 1)
    local deco = guy:limb("UpperBody"):object():decorate(spr, { y = 0.1, behind = true })
    expect(deco and deco:exists(), "no decoration")
    local lt = brick:light(1, 0, 0, 1, 1); expect(lt and lt:exists()); lt.visible = false
    expect(not brick.bulletproof); brick.bulletproof = true; expect(brick.bulletproof)
    guy:paint{ ["*"] = ppg.texture("pixel.png") }
    local hit = ppg.raycast(guy:limb("Head"):object().x - 3, guy:limb("Head"):object().y, 1, 0, 10, guy)
    expect(hit == nil or hit:person() ~= guy, "raycast did not ignore the person")
  end)
  ppg.after(1.0, function()
    check("kill and heal", function()
      local person = human:person()
      person:kill()
      ppg.after(0.5, function()
        check("person died", function() expect(not person.alive, "still alive after kill") end)
        person:heal()
        ppg.after(0.5, function()
          check("person revived", function() expect(person.alive, "not alive after heal") end)
          check("destroy", function()
            brick:destroy()
            ppg.after(0.1, function()
              check("destroyed handle reports gone", function()
                expect(not brick:exists())
                expect(not pcall(function() return brick.x end))
              end)
              print(string.format("PROBE DONE passed=%d failed=%d", passed, failed))
            end)
          end)
        end)
      end)
    end)
  end)
end)
